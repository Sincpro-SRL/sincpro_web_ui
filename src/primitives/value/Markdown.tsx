"use client";

import { Streamdown } from "streamdown";

/* ==================================================================== *
 *  MARKDOWN — a document written in markdown, drawn as text.
 *
 *  Context: a message, a note or a README arrives as markdown. It is drawn
 *  with streamdown (Vercel, Apache-2.0, published 2026-10), which parses it
 *  block by block and passes the result through `rehype-sanitize`: a script,
 *  an `onerror` or a `javascript:` link in the source is removed before it
 *  reaches the page. Links follow streamdown's `linkSafety` setting; we keep
 *  its default and check it in the story.
 *
 *  ── Streaming is a state the caller knows, not one we guess ─────────
 *
 *  `streaming` is true while the text is still arriving (an AI answer, a
 *  message being written). Then an unfinished table or an open code fence is
 *  held back until it can be read, instead of flashing broken markup. A
 *  finished document is `streaming={false}` — the default.
 *
 *  ── Nothing to add ──────────────────────────────────────────────────
 *
 *  streamdown's Tailwind classes and its animations come with `tokens.css`,
 *  which the application already imports for the whole design system. The
 *  classes are generated by the same `@source` every component relies on.
 *
 * ==================================================================== */

export type MarkdownProps = {
  /** The markdown source. Plain text is valid markdown too. */
  children: string;
  /** The text is still arriving: hold back what cannot be read yet. */
  streaming?: boolean;
  /** The accessible name when the document is the point of the screen. */
  label?: string;
};

/* The document's own rhythm, in tokens. The arbitrary variants only select the
   descendants; every value is a token. A heading is the same size as the rest
   of the product's headings, not a browser default. */
const BODY =
  "max-w-prose text-body leading-relaxed text-ink " +
  "[&_p]:mt-2 [&_p:first-child]:mt-0 " +
  "[&_h1]:mt-4 [&_h1]:text-display [&_h1]:font-semibold " +
  "[&_h2]:mt-4 [&_h2]:text-lead [&_h2]:font-semibold " +
  "[&_h3]:mt-3 [&_h3]:text-body [&_h3]:font-semibold " +
  "[&_ul]:mt-2 [&_ul]:list-disc [&_ul]:pl-5 [&_ol]:mt-2 [&_ol]:list-decimal [&_ol]:pl-5 " +
  "[&_a]:text-primary [&_a]:underline [&_a]:underline-offset-4 " +
  "[&_code]:rounded-control [&_code]:bg-ink/6 [&_code]:px-1 [&_code]:font-mono [&_code]:text-micro " +
  "[&_blockquote]:mt-2 [&_blockquote]:border-l-2 [&_blockquote]:border-line-strong [&_blockquote]:pl-3 [&_blockquote]:text-muted";

export function Markdown({ children, streaming = false, label }: MarkdownProps) {
  return (
    <div
      role={label === undefined ? undefined : "document"}
      aria-label={label}
      className={BODY}
    >
      <Streamdown mode={streaming ? "streaming" : "static"} controls={false}>
        {children}
      </Streamdown>
    </div>
  );
}
