/* ==================================================================== *
 *  EL CASTELLANO DEL SISTEMA.
 *
 *  El sistema viene en inglés de fábrica y éste es su castellano, de una sola
 *  vez y para todos: la vitrina, que se lee en castellano como el resto de la
 *  documentación, y la aplicación, que lo instala y sólo encima cambia lo que
 *  quiera decir distinto.
 *
 *  ── Por qué vive ACÁ y no en cada consumidor ────────────────────────
 *
 *  Porque son las palabras del SISTEMA: cómo se llama «cualquiera», cómo se lee
 *  «está entre», qué dice una lista vacía. Escritas en cada consumidor son la
 *  misma tabla mantenida en dos lugares, y el día que una gana una palabra la
 *  otra la muestra en inglés en medio de una pantalla en castellano — que es
 *  exactamente lo que pasaba.
 *
 *  Lo que NO está acá es lo que dice el PRODUCTO: «importá tus facturas», el nombre de
 *  una vista, el rótulo de un campo. Eso lo sabe quien lo escribió.
 *
 *  Que no se quede corto lo garantiza `tests/copy.test.tsx`: compara sus hojas
 *  contra las que el sistema sabe decir. Una clave nueva en `copy.tsx` sin su
 *  palabra acá rompe la prueba, en vez de aparecer en inglés sin que nadie lo
 *  note.
 * ==================================================================== */

